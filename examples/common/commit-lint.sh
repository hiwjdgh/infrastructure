#!/usr/bin/env bash
# COPY INTO EVERY APP REPO: .github/scripts/commit-lint.sh  (commit-check.yml, .githooks/commit-msg 에서 사용)
# Usage: commit-lint.sh --file <commit-msg-file>   (git commit-msg hook)
#        commit-lint.sh "<message>"                (PR 제목 / 커밋 제목 검사)
#        commit-lint.sh --guide                     (규칙 안내만 출력)
# 첫 줄(제목)이 Conventional Commits 규칙에 맞으면 0, 아니면 규칙 안내를 stderr 로 출력하고 1 로 종료합니다.
set -euo pipefail
export LC_ALL=C.UTF-8

TYPES='feat|fix|perf|refactor|docs|style|test|build|ci|chore|revert'
MAX_LEN=100

guide() {
  cat <<'GUIDE'
커밋 메시지 규칙 (Conventional Commits)

  <타입>: <설명>
  <타입>(<범위>): <설명>
  <타입>(<범위>)!: <설명>      ← 호환성이 깨지는 변경 (major 버전 업)

  타입       의미                        버전
  feat       기능 추가                   minor
  fix        버그 수정                   patch
  perf       성능 개선                   patch
  refactor   리팩터링 (동작 변화 없음)   patch
  docs       문서                        patch
  style      포맷, 공백 등               patch
  test       테스트                      patch
  build      빌드, 의존성                patch
  ci         CI 설정                     patch
  chore      기타 잡무                   patch
  revert     되돌리기                    patch

  - 타입은 소문자, 콜론(:) 뒤에 공백 한 칸
  - 설명은 1~100자, 한글 사용 가능

  예시
    feat: 소셜 로그인 추가
    fix(auth): 토큰 만료 시 무한 리다이렉트 수정
    feat(api)!: 주문 조회 응답 형식 변경
GUIDE
}

case "${1:-}" in
  --guide) guide; exit 0 ;;
  --file)  MSG="$(cat "${2:?commit message file required}")" ;;
  "")      echo 'Usage: commit-lint.sh --file <path> | "<message>" | --guide' >&2; exit 2 ;;
  *)       MSG="$1" ;;
esac

# First line that is not a git comment; strip CR from Windows tools.
HEADER="$(printf '%s\n' "$MSG" | tr -d '\r' | grep -v '^#' | grep -m 1 -v '^[[:space:]]*$' || true)"

# Messages generated by git / GitHub are always allowed.
if [[ "$HEADER" =~ ^(Merge\ |Revert\ \"|(fixup|squash|amend)!\ ) ]]; then exit 0; fi

RE="^($TYPES)(\\([^()]+\\))?!?: ([^[:space:]].*)$"
if [[ "$HEADER" =~ $RE ]]; then
  DESC="${BASH_REMATCH[3]}"
  if (( ${#DESC} <= MAX_LEN )); then exit 0; fi
  REASON="설명이 너무 깁니다 (${#DESC}자 > ${MAX_LEN}자)"
elif [[ -z "$HEADER" ]]; then
  REASON="메시지가 비어 있습니다"
elif [[ "$HEADER" =~ ^($TYPES)(\([^()]+\))?!?:[^[:space:]] ]]; then
  REASON="콜론(:) 뒤에 공백이 필요합니다"
elif [[ "$HEADER" =~ ^($TYPES)(\([^()]+\))?!?:[[:space:]]*$ ]]; then
  REASON="설명이 비어 있습니다"
elif [[ "$HEADER" =~ ^[A-Za-z]+(\([^()]*\))?!?: ]]; then
  REASON="허용되지 않은 타입입니다 (소문자 ${TYPES//|/, } 중 하나)"
else
  REASON="'<타입>: <설명>' 형식이 아닙니다"
fi

{
  echo "✖ 커밋 메시지 규칙 위반: $REASON"
  echo "  입력: $HEADER"
  echo
  guide
} >&2
exit 1
